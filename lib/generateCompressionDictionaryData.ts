// Generates worker-src/routes/compression-dictionary/data.ts
// Requires the `brotli` and `zstd` CLIs (eg `brew install brotli zstd`), since
// Node's zlib doesn't support custom brotli dictionaries.
//
// Run with: node lib/generateCompressionDictionaryData.ts
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const threeMath = resolve(root, 'node_modules/three/src/math');
const dictionaryPath = resolve(threeMath, 'Vector3.js');
const resourcePath = resolve(threeMath, 'Vector4.js');
const outPath = resolve(
  root,
  'worker-src/routes/compression-dictionary/data.ts',
);

const dictionary = readFileSync(dictionaryPath);
const resource = readFileSync(resourcePath);
const dictionaryHash = createHash('sha256').update(dictionary).digest();

const br = execFileSync('brotli', ['-c', '-q', '11', resourcePath]);
const brWithDict = execFileSync('brotli', [
  '-c',
  '-q',
  '11',
  '-D',
  dictionaryPath,
  resourcePath,
]);

// Dictionary-compressed brotli format:
// 4 byte magic number, then the SHA-256 of the dictionary, then the brotli stream.
const dcb = Buffer.concat([
  Buffer.from([0xff, 0x44, 0x43, 0x42]),
  dictionaryHash,
  brWithDict,
]);

const zstd = execFileSync('zstd', ['-c', '-q', '-19', resourcePath]);
const zstdWithDict = execFileSync('zstd', [
  '-c',
  '-q',
  '-19',
  '-D',
  dictionaryPath,
  resourcePath,
]);

// Dictionary-compressed zstd format:
// 8 byte magic number (a zstd skippable frame header), then the SHA-256 of the
// dictionary, then the zstd stream.
const dcz = Buffer.concat([
  Buffer.from([0x5e, 0x2a, 0x4d, 0x18, 0x20, 0x00, 0x00, 0x00]),
  dictionaryHash,
  zstdWithDict,
]);

writeFileSync(
  outPath,
  `// Generated by lib/generateCompressionDictionaryData.ts - do not edit.
// Dictionary: three/src/math/Vector3.js
// Resource: three/src/math/Vector4.js

export const dictionary = ${JSON.stringify(dictionary.toString('utf8'))};
export const resource = ${JSON.stringify(resource.toString('utf8'))};
/** Structured-field byte sequence, as sent in Available-Dictionary */
export const dictionaryHash = ${JSON.stringify(`:${dictionaryHash.toString('base64')}:`)};
export const resourceBrBase64 = ${JSON.stringify(br.toString('base64'))};
export const resourceDcbBase64 = ${JSON.stringify(dcb.toString('base64'))};
export const resourceZstdBase64 = ${JSON.stringify(zstd.toString('base64'))};
export const resourceDczBase64 = ${JSON.stringify(dcz.toString('base64'))};
`,
);

console.log(
  `Wrote ${outPath}\n` +
    `resource: ${resource.length} bytes, br: ${br.length} bytes, dcb: ${dcb.length} bytes, ` +
    `zstd: ${zstd.length} bytes, dcz: ${dcz.length} bytes`,
);
